#!/usr/bin/env bash
# Rebuild the projects table in README.md from projects/*/README.md.
# Reads each project's first "# " heading and its "**Status:**" line.
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
readme="$root/README.md"
start='<!-- PROJECTS-INDEX:START -->'
end='<!-- PROJECTS-INDEX:END -->'

table=$(mktemp)
trap 'rm -f "$table"' EXIT

found=0
{
  echo "| # | Project | Status |"
  echo "| --- | --- | --- |"
  for f in "$root"/projects/project-*/README.md; do
    [ -e "$f" ] || continue
    found=1
    folder=$(basename "$(dirname "$f")")
    num=$(echo "$folder" | sed -E 's/^project-([0-9]+)-.*/\1/')
    title=$(grep -m1 '^# ' "$f" | sed 's/^# //')
    status=$(grep -m1 '^\*\*Status:\*\*' "$f" | sed 's/^\*\*Status:\*\* *//')
    echo "| $num | [$title](projects/$folder/) | ${status:-Unknown} |"
  done
} > "$table"

if [ "$found" -eq 0 ]; then
  echo "_No projects yet. The table is generated by \`scripts/update-index.sh\`._" > "$table"
fi

awk -v start="$start" -v end="$end" -v tablefile="$table" '
  $0 == start { print; while ((getline line < tablefile) > 0) print line; skip = 1; next }
  $0 == end   { skip = 0 }
  !skip       { print }
' "$readme" > "$readme.tmp" && mv "$readme.tmp" "$readme"

echo "Project index updated."
